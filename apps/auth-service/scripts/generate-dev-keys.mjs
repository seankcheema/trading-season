#!/usr/bin/env node
/**
 * Generates an RSA keypair for local development and prints it as environment
 * variables on stdout. Writes nothing to disk — pipe it where you want it:
 *
 *   node apps/auth-service/scripts/generate-dev-keys.mjs >> .env
 *
 * Keys are emitted with literal \n escapes so they survive .env files, shells
 * and docker-compose, all of which mangle real newlines in a value.
 * JwtKeysService.normalizeKey() converts them back on load.
 *
 * These are development keys. Production keys should come from a secret
 * manager and must never pass through a file in the repository.
 */
import { generateKeyPairSync } from 'node:crypto';

const { privateKey, publicKey } = generateKeyPairSync('rsa', {
  modulusLength: 2048,
});

const escape = (pem) => pem.trimEnd().replace(/\n/g, '\\n');

const privatePem = privateKey.export({ type: 'pkcs8', format: 'pem' });
const publicPem = publicKey.export({ type: 'spki', format: 'pem' });

process.stdout.write(
  [
    '',
    '# Generated by apps/auth-service/scripts/generate-dev-keys.mjs',
    '# Development only. Never commit these.',
    `JWT_PRIVATE_KEY="${escape(privatePem)}"`,
    `JWT_PUBLIC_KEY="${escape(publicPem)}"`,
    'JWT_ISSUER=https://auth.dualeapa.local',
    '',
  ].join('\n'),
);
